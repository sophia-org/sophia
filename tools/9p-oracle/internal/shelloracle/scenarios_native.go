package shelloracle

func (r *runner) nativeScenario() {
	s := r.connect("launcher", 4096)
	defer s.close()
	roleNegotiate(s, 7, 0x9a0, 0x9a0)
	r.check(65, true)
	s.phase("publish")
	catalog := roleObject(s, 3, 3)
	r.check(66, u16(catalog.body, 24) == 3 && u16(catalog.body, 26) == 0)
	s.phase("opening")
	opening := s.expect(38)
	need(u64(opening.body, 24) == 7 && u64(opening.body, 48) == 3 && u64(opening.body, 56) == 1, "opening")
	s.ack(opening)
	r.check(67, true)
	roleAllocation(s, true)
	r.check(68, true)
	smallResource(s)
	initialPermit := rolePermit(s, 1)
	r.check(69, true)
	generation := r.roleCandidateControls(s, true, 3, initialPermit)
	r.roleFatal("launcher-permit-revoked", true)
	permit := rolePermit(s, 100)
	s.phase("hold-candidates")
	id := s.submit(267, roleCandidate(true, permit, generation, 3, 1))
	s.ack(s.custody(id, 267))
	s.noEvents()
	r.check(70, true)
	s.phase("release-candidates")
	prepared := roleOutcome(s, generation, 1, 0)
	r.check(71, true)
	s.phase("owner-drained")
	s.noEvents()
	r.check(72, true)
	s.phase("present")
	presented := roleOutcome(s, generation, 2, 0)
	r.check(73, presented.sequence > prepared.sequence && u64(presented.body, 52) != 0)
	focus := s.expect(39)
	s.ack(focus)
	r.check(74, u64(focus.body, 24) == 7 && u64(focus.body, 32) == 2 && u64(focus.body, 48) == 1 && u64(focus.body, 64) == 3 && u64(focus.body, 72) == generation && u64(focus.body, 80) == u64(presented.body, 52) && u64(focus.body, 96) == 1 && u64(focus.body, 104) != 0)
	s.phase("text")
	input := s.expect(41)
	s.ack(input)
	r.check(75, u16(input.body, 136) == 1 && string(roleText(input.body[138:], 256)) == "a" && u64(input.body, 120) > 1 && identical(input.body[8:112], focus.body[8:112]))
	textAck := nativeInputAckBody(input, 700, 1)
	id = s.submit(268, textAck)
	s.ack(s.custody(id, 268))
	s.phase("ack-consumed")
	s.noEvents()
	r.check(76, true)
	activation := nativeActivateBody(focus.body, 701, u64(input.body, 112), 1, 2, 1)
	id = s.submit(269, activation)
	s.custody(id, 269)
	e := s.expect(42)
	need(identical(e.body[:132], activation), "stale native echo")
	r.check(77, u16(e.body, 132) == 2 && u16(e.body, 134) == 1)
	s.ack(e)
	generation++
	permit = rolePermit(s, 101)
	id = s.submit(267, roleCandidate(true, permit, generation, 3, u64(input.body, 120)))
	s.custody(id, 267)
	roleOutcome(s, generation, 1, 0)
	s.phase("present")
	roleOutcome(s, generation, 2, 0)
	revoked := s.expect(40)
	need(identical(revoked.body[8:112], focus.body[8:112]) && u16(revoked.body, 112) == 1, "superseded focus")
	s.ack(revoked)
	fresh := s.expect(39)
	s.ack(fresh)
	r.check(78, u64(fresh.body, 96) == u64(input.body, 120) && u64(fresh.body, 104) != u64(focus.body, 104))
	s.phase("accept")
	accept := s.expect(41)
	s.ack(accept)
	r.check(79, u16(accept.body, 136) == 17 && len(roleText(accept.body[138:], 256)) == 0 && u64(accept.body, 120) == u64(fresh.body, 96))
	s.phase("hold-activation")
	activation = nativeActivateBody(fresh.body, 702, u64(accept.body, 112), u64(accept.body, 120), 1, 1)
	id = s.submit(269, activation)
	s.ack(s.custody(id, 269))
	s.noEvents()
	r.check(80, true)
	s.phase("release-activation")
	e = s.expect(42)
	r.check(81, identical(e.body[:132], activation) && u16(e.body, 132) == 1 && u16(e.body, 134) == 0)
	s.ack(e)
	id = s.submit(268, nativeInputAckBody(accept, 703, 1))
	s.ack(s.custody(id, 268))
	id = s.submit(268, nativeInputAckBody(input, 704, 1))
	s.ack(s.custody(id, 268))
	s.phase("stale-ack-consumed")
	s.noEvents()
	r.check(82, true)
	s.phase("one-admission")
	s.phase("close")
	revoked = s.expect(40)
	s.ack(revoked)
	r.check(83, identical(revoked.body[8:112], fresh.body[8:112]) && u16(revoked.body, 112) == 12)
	e = s.expect(43)
	s.ack(e)
	r.check(84, u64(e.body, 24) == 7 && u16(e.body, 32) == 12)
}
