package shelloracle

func (r *runner) mainScenario() {
	s := r.connect("main", 4096)
	defer s.close()
	for _, test := range []struct {
		kind  uint16
		body  []byte
		check int
	}{{257, allocation(40, 1, 2), 4}, {262, candidate(999, 1), 5}} {
		s.stage(s.encoded(test.kind, 1, test.body), 0)
		r.check(test.check, errno(s.submitRaw(s.encoded(test.kind, 1, test.body))) == 13)
		s.w.clunk(5)
		s.noEvents()
	}
	s.negotiate()
	r.check(1, s.epoch != 1)
	raw := s.encoded(256, s.nextID, offer())
	s.stage(raw, 0)
	r.check(3, errno(s.submitRaw(raw)) == 114)
	s.w.clunk(5)
	s.noEvents()
	s.w.file(10, 0, "limits")
	limits := s.object(10)
	s.w.clunk(10)
	r.check(6, limits.kind == 1 && u64(limits.body, 0) == s.epoch && u64(limits.body, 8) == 1)
	s.phase("publish")
	a := s.expect(19)
	r.check(8, u16(a.body, 0) == 2 && u64(a.body, 8) == 3)
	s.ack(a)
	qid := s.w.file(10, 0, "outputs")
	old := s.object(10)
	r.check(7, old.kind == 2 && u64(old.body, 24) == 3 && u32(old.body, 32) == 1)
	attr := s.w.getattr(10)
	r.check(9, qid == u64(a.body, 16) && u64(attr, 13) == qid)
	s.w.walk(11, "outputs")
	r.check(10, errno(s.w.open(11, 0)) == 16)
	s.w.clunk(11)
	s.phase("republish")
	a = s.expect(19)
	s.ack(a)
	again := s.object(10)
	r.check(11, identical(old.bytes, again.bytes))
	s.w.clunk(10)
	fresh := s.w.file(10, 0, "outputs")
	r.check(12, fresh != qid && fresh == u64(a.body, 16))
	current := s.object(10)
	s.w.clunk(10)
	r.check(13, u64(current.body, 24) == 4 && u64(a.body, 8) == 4)
	id := s.submit(257, allocation(40, 1, 2))
	custody := s.custody(id, 257)
	grant := s.expect(32)
	r.check(14, u64(grant.body, 0) == 40 && u64(grant.body, 24) == 1 && u16(grant.body, 32) == 1)
	r.check(16, u64(grant.body, 40) == 2 && u64(grant.body, 56) == 1 && u32(grant.body, 104) == 64 && u32(grant.body, 108) == 32 && u64(grant.body, 88) == 5)
	r.check(36, custody.sequence < grant.sequence)
	r.check(46, u64(custody.body, 0) == id && id != 40 && u64(grant.body, 0) == 40)
	s.ack(grant)
	id = s.submit(257, allocation(41, 2, 99))
	s.custody(id, 257)
	rejected := s.expect(32)
	r.check(15, u64(rejected.body, 0) == 41 && u64(rejected.body, 24) == 2 && u16(rejected.body, 32) == 2)
	s.ack(rejected)
	r.uploads(s)
	smallResource(s)
	id = s.submit(263, demand(90, 1))
	s.custody(id, 263)
	permit := s.expect(36)
	s.ack(permit)
	r.check(27, u64(permit.body, 40) == 1 && u16(permit.body, 56) == 1 && u64(permit.body, 48) != 0)
	id = s.submit(262, candidate(u64(permit.body, 48), 1))
	r.check(28, u64(s.custody(id, 262).body, 0) == id)
	prepared := s.expect(35)
	r.check(29, u16(prepared.body, 48) == 1 && u64(prepared.body, 24) == 1)
	s.ack(prepared)
	presented := s.expect(35)
	r.check(30, u16(presented.body, 48) == 2 && u64(presented.body, 52) == 9 && presented.sequence > prepared.sequence)
	s.ack(presented)
	s.phase("action")
	action := s.expect(37)
	expectedAction := grantBody(120, 150)
	for at, value := range map[int]uint64{8: s.epoch, 24: 2, 32: 1, 40: 1, 48: 9, 56: 4, 64: 1, 72: 1, 80: 1, 88: 1, 96: 1, 104: 11} {
		p64(expectedAction, at, value)
	}
	p16(expectedAction, 112, 1)
	r.check(34, identical(action.body, expectedAction))
	ack := append([]byte(nil), action.body...)
	p64(ack, 0, 151)
	p16(ack, 112, 1)
	p16(ack, 114, 0)
	s.ack(action)
	id = s.submit(265, ack)
	e := s.custody(id, 265)
	s.ack(e)
	s.phase("action-acked")
	r.check(35, u64(e.body, 0) == id)
	id = s.submit(263, demand(160, 2))
	s.custody(id, 263)
	permit = s.expect(36)
	s.ack(permit)
	id = s.submit(264, cancelDemand(161, 2, u64(permit.body, 48)))
	s.custody(id, 264)
	cancelled := s.expect(36)
	r.check(32, u16(cancelled.body, 56) == 3 && u16(cancelled.body, 58) == 11 && u64(cancelled.body, 40) == 2 && u64(cancelled.body, 48) == u64(permit.body, 48))
	s.ack(cancelled)
}
func (r *runner) uploads(s *session) {
	id := s.submit(258, resourceBegin(1))
	s.custody(id, 258)
	admitted := s.status(1, 1)
	r.check(17, u64(admitted.body, 48) == 65536)
	s.w.file(20, 1, "upload", "0")
	pixels := make([]byte, 65536)
	n := wrote(s.w.write(20, 0, pixels[:1000]))
	r.check(18, n == 1000)
	offset := 1000
	short := false
	bounded := true
	for offset < len(pixels) {
		end := offset + int(s.w.msize) - 23
		if end > len(pixels) {
			end = len(pixels)
		}
		n = wrote(s.w.write(20, uint64(offset), pixels[offset:end]))
		need(n > 0 && int(n) <= end-offset, "upload progress")
		if int(n) < end-offset {
			short = true
			need(offset+int(n) == 57344, "canonical boundary")
		}
		bounded = bounded && end-offset <= 4073
		offset += int(n)
	}
	r.check(19, bounded && offset == 65536)
	r.check(20, short)
	end := resourceIdentity(56, 1, 80)
	p64(end, 40, 65536)
	p32(end, 48, 2)
	id = s.submit(259, end)
	s.custody(id, 259)
	s.status(1, 2)
	r.check(21, true)
	r.check(24, errno(s.w.write(20, 0, pixels[:4])) == 116)
	id = s.submit(258, resourceBegin(2))
	s.custody(id, 258)
	s.status(2, 1)
	s.w.file(21, 1, "upload", "0")
	id = s.submit(260, resourceIdentity(40, 2, 82))
	s.custody(id, 260)
	s.status(2, 4)
	r.check(22, true)
	r.check(25, errno(s.w.write(21, 0, pixels[:4])) == 116)
	id = s.submit(258, resourceBegin(3))
	s.custody(id, 258)
	s.status(3, 1)
	s.w.file(22, 1, "upload", "0")
	s.w.clunk(20)
	s.w.clunk(21)
	r.check(26, wrote(s.w.write(22, 0, pixels[:4])) == 4)
	s.w.clunk(22)
	s.status(3, 4)
	r.check(23, true)
}
func smallResource(s *session) {
	b := resourceBegin(5)
	p32(b, 48, 2)
	p32(b, 52, 1)
	p32(b, 68, 1)
	p64(b, 72, 8)
	id := s.submit(258, b)
	s.custody(id, 258)
	s.status(5, 1)
	s.w.file(23, 1, "upload", "0")
	need(wrote(s.w.write(23, 0, make([]byte, 8))) == 8, "small resource write")
	b = resourceIdentity(56, 5, 86)
	p64(b, 40, 8)
	p32(b, 48, 1)
	id = s.submit(259, b)
	s.custody(id, 259)
	s.status(5, 2)
	s.w.clunk(23)
}
